# Un programme calculant l'aire et le périmètre d'un cercle de rayon r, entré
# au clavier par l'utilisateur. (Nous prenons la valeur 
#                                approximative de pi, soit 3.14)

print('**** Bienvenue ! ****')
r = float(input("Entrez la valeur du rayon du cercle: "))
print("L'aire du cercle vaut:", 3.14*r**2, "cm^2")
print("Le périmètre du cercle vaut:", 2*3.14*r,"cm")
